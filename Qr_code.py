def _component_dir() -> str:
    folder = Path(__file__).resolve().parent / "qr_component"
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / "index.html"
    data = base64.b64decode("".join(_COMPONENT_HTML.split()))
    if not target.exists() or target.read_bytes() != data:
        target.write_bytes(data)
    return str(folder)


def _hex_rgb(value: str):
    raw = (value or "").lstrip("#")
    return tuple(int(raw[i:i + 2], 16) for i in (0, 2, 4))


def _generate_png(content, foreground, background, dot_style, logo_data):
    qr = qrcode.QRCode(
        version=None,
        error_correction=qrcode.constants.ERROR_CORRECT_H,
        box_size=10,
        border=1,
    )
    qr.add_data(content)
    qr.make(fit=True)

    if dot_style == "rounded":
        image = qr.make_image(
            image_factory=StyledPilImage,
            module_drawer=RoundedModuleDrawer(radius_ratio=0.8),
            color_mask=SolidFillColorMask(
                front_color=_hex_rgb(foreground),
                back_color=_hex_rgb(background),
            ),
        )
    elif dot_style == "soft":
        image = qr.make_image(
            image_factory=StyledPilImage,
            module_drawer=CircleModuleDrawer(),
            color_mask=SolidFillColorMask(
                front_color=_hex_rgb(foreground),
                back_color=_hex_rgb(background),
            ),
        )
    else:
        image = qr.make_image(
            fill_color=foreground,
            back_color=background,
        )

    image = image.convert("RGBA")

    if logo_data:
        raw = logo_data.split(",", 1)[-1]
        logo = Image.open(io.BytesIO(base64.b64decode(raw))).convert("RGBA")
        logo_size = int(image.width * 0.15)
        logo.thumbnail((logo_size, logo_size), Image.Resampling.LANCZOS)
        x = (image.width - logo.width) // 2
        y = (image.height - logo.height) // 2
        image.alpha_composite(logo, (x, y))

    output = io.BytesIO()
    image.save(output, format="PNG")
    return output.getvalue()


