if "handled_nonce" not in st.session_state:
    st.session_state.handled_nonce = None

event = _qr_ui(
    qr_response=st.session_state.qr_response,
    height=900,
    default=None,
    key="qr_studio_ui",
)

if isinstance(event, dict) and event.get("action") == "generate":
    nonce = event.get("nonce")
    if nonce and nonce != st.session_state.handled_nonce:
        st.session_state.handled_nonce = nonce
        content = (event.get("content") or "").strip()
        try:
            if not content:
                raise ValueError("Content is required")
            png = _generate_png(
                content,
                event.get("foreground") or "#000000",
                event.get("background") or "#ffffff",
                event.get("dot_style") or "square",
                event.get("logo") or "",
            )
            st.session_state.qr_response = {
                "nonce": nonce,
                "ok": True,
                "image": "data:image/png;base64," + base64.b64encode(png).decode("ascii"),
            }
        except Exception:
            st.session_state.qr_response = {
                "nonce": nonce,
                "ok": False,
                "error": "QR generation failed",
            }
        st.rerun()